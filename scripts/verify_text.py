"""Compare the Chalisa verse text against two independent sources and write docs/TEXT_REVIEW.md.

This is a *reporting* tool for human gate H1. It never sets `verified_flag` and never
approves anything: it only shows where the stored Devanagari differs from the sources.

Usage:
    python scripts/verify_text.py --a <file-or-url> --b <file-or-url>

Exit codes: 0 = both sources agree with every unit, 1 = differences/missing text,
2 = no sources supplied (H1 still needs a human).
"""
from __future__ import annotations
import argparse
import difflib
import json
import re
import sys
import urllib.request
from pathlib import Path
from typing import Dict, List

ROOT = Path(__file__).resolve().parents[1]
PACK = ROOT / "data" / "packs" / "shiv_chalisa" / "verses.json"
OUT = ROOT / "docs" / "TEXT_REVIEW.md"

_PUNCT = re.compile(r"[।॥,.;:!?\"'()\[\]\-–—|]+")


def normalize(text: str) -> List[str]:
    return _PUNCT.sub(" ", text).split()


def load_source(spec: str) -> str:
    if spec.startswith(("http://", "https://")):
        with urllib.request.urlopen(spec, timeout=30) as r:      # noqa: S310 - explicit user URL
            return r.read().decode("utf-8", errors="replace")
    return Path(spec).read_text(encoding="utf-8", errors="replace")


def locate(source_words: List[str], unit_text: str) -> tuple[int, int]:
    """Return (start, end) word indices of this unit in the source, or (-1, -1)."""
    anchor = normalize(unit_text)[:3]
    if not anchor:
        return -1, -1
    n = len(anchor)
    for i in range(len(source_words) - n + 1):
        if source_words[i:i + n] == anchor:
            return i, i + n
    return -1, -1


def compare_unit(unit_text: str, source_text: str, next_text: str | None = None) -> dict:
    """Compare one unit against the source span it occupies.

    The span runs from this unit's anchor to the next unit's anchor, so trailing
    differences inside the verse are visible. Without a next unit we can only
    compare an equal-length window; that is recorded as the last-unit fallback.
    """
    src = normalize(source_text)
    unit = normalize(unit_text)
    start, _ = locate(src, unit_text)
    if start < 0:
        return {"status": "MISSING", "ratio": 0.0, "quote": ""}
    next_start = locate(src, next_text)[0] if next_text else -1
    if next_start > start:
        window = src[start:next_start]
    else:
        window = src[start:start + len(unit)]
    ratio = difflib.SequenceMatcher(a=unit, b=window, autojunk=False).ratio()
    if ratio >= 0.97:
        status = "MATCH"
    elif ratio >= 0.85:
        status = "MINOR_DIFF"
    else:
        status = "DIFF"
    quote = " ".join(window[:len(unit) + 2])
    return {"status": status, "ratio": round(ratio, 3), "quote": quote}


def build_review(units: List[dict], sources: Dict[str, str]) -> List[dict]:
    rows = []
    for i, u in enumerate(units):
        nxt = units[i + 1]["devanagari"] if i + 1 < len(units) else None
        row = {"seq": u.get("seq"), "text": u["devanagari"], "sources": {}}
        for name, text in sources.items():
            row["sources"][name] = compare_unit(u["devanagari"], text, nxt)
        rows.append(row)
    return rows


def write_markdown(rows: List[dict], sources: Dict[str, str]) -> None:
    names = list(sources)
    lines = ["# Shiv Chalisa text review (H1 evidence)", "",
             "Generated by `scripts/verify_text.py`. This report does not change `verified_flag`;",
             "a human must review and approve the verse text.", "",
             f"Sources: {', '.join(f'`{n}`' for n in names)}", "",
             "| seq | " + " | ".join(names) + " |",
             "|---|" + "---|" * len(names)]
    for r in rows:
        cells = [f"{r['sources'][n]['status']} ({r['sources'][n]['ratio']})" for n in names]
        lines.append(f"| {r['seq']} | " + " | ".join(cells) + " |")
    diffs = [r for r in rows if any(s["status"] != "MATCH" for s in r["sources"].values())]
    if diffs:
        lines += ["", "## Discrepancies", ""]
        for r in diffs:
            lines.append(f"### {r['seq']}. {r['text']}")
            for n in names:
                s = r["sources"][n]
                lines.append(f"- **{n}**: {s['status']} ({s['ratio']}) — `{s['quote'][:200]}`")
            lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--a", help="first source (file path or http(s) URL)")
    ap.add_argument("--b", help="second source (file path or http(s) URL)")
    args = ap.parse_args()
    if not args.a or not args.b:
        print("No sources supplied. H1 (verse text verification) still requires a human.")
        print("Re-run with: python scripts/verify_text.py --a <source1> --b <source2>")
        return 2
    units = json.loads(PACK.read_text(encoding="utf-8"))
    sources = {"source_a": load_source(args.a), "source_b": load_source(args.b)}
    rows = build_review(units, sources)
    write_markdown(rows, sources)
    bad = [r for r in rows if any(s["status"] != "MATCH" for s in r["sources"].values())]
    print(f"units: {len(rows)}, discrepancies: {len(bad)} -> {OUT.relative_to(ROOT)}")
    print("NOTE: verified_flag was not touched; a human must approve H1.")
    return 0 if not bad else 1


if __name__ == "__main__":
    sys.exit(main())
